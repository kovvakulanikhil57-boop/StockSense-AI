-- ==============================================================================
-- StockSense AI: University Stationery Store and Delivery Management System
-- PostgreSQL Schema for Supabase
-- ==============================================================================
-- Note: PostgreSQL identifiers are case-insensitive unless quoted.
-- Creating tables in lowercase allows queries like "SELECT * FROM Users" and
-- "SELECT * FROM users" to both resolve seamlessly.

-- ------------------------------------------------------------------------------
-- 0. Extensions & Helper Functions
-- ------------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- Automated updated_at timestamp trigger function
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

